//! wg-config: configuration model, TOML parsing, migration, writer (contract section 13.5, file F01).
//!
//! The model mirrors `src/workgraph/config/settings.py`. A document is a TOML table; it is validated
//! against the model with Pydantic's lax-mode rules and Pydantic's error shapes (`type`, `loc`,
//! `msg`), its defaults are filled in, and the result is dumped in declaration order, as
//! `model_dump(mode="json")` does. The writer reproduces `tomli_w`'s output for the shapes Workgraph
//! writes.
//!
//! Everything here is in memory: the shell crate reads and writes the files. [`ConfigFiles`] holds
//! the texts of `config.toml` and of the workspace files, so the whole store (validation, migration,
//! merge) is a pure function of those texts.
//!
//! Vectors: `golden/config/*.json`, generated by `tools/golden/gen_config.py` (GV-11).

