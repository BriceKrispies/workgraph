//! Platform storage locations (contract section 7, files F01 to F11).
//!
//! The rules are platformdirs' (`user_config_dir`, `user_data_dir` and `user_log_dir` with
//! `appname = "workgraph"`, `appauthor = False`), with `WORKGRAPH_HOME` relocating everything under
//! one directory. The function is pure: the caller passes a snapshot of the variables it needs in
//! an [`Environment`], so no process state is read here. Path text is handled by this module
//! rather than `std::path`, so Windows and POSIX rules apply whatever the host operating system is.
//!
//! Vectors: `golden/paths/vectors.json`, generated by `tools/golden/gen_paths.py`.

use core::fmt;

/// The operating system whose platformdirs rules apply.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Os {
    Windows,
    Linux,
    MacOs,
}

/// The environment variables the rules read, as the caller observed them.
///
/// Empty strings count as unset, as they do in platformdirs and in the Python `AppPaths`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Environment {
    pub os: Os,
    pub workgraph_home: Option<String>,
    /// `HOME` on Linux and macOS, `USERPROFILE` on Windows.
    pub home: Option<String>,
    /// `LOCALAPPDATA` (Windows only). When unset, `<home>\AppData\Local` is used.
    pub local_appdata: Option<String>,
    pub xdg_config_home: Option<String>,
    pub xdg_data_home: Option<String>,
    pub xdg_state_home: Option<String>,
}

/// Why the locations could not be resolved.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PathsError {
    /// Neither `HOME` (`USERPROFILE` on Windows) is set, and a path needs it.
    NoHome,
    /// `WORKGRAPH_HOME` is relative. The caller makes it absolute against the working directory
    /// before resolving, since this function has no access to that directory.
    RelativeWorkgraphHome(String),
}

impl fmt::Display for PathsError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::NoHome => {
                formatter.write_str("no home directory: HOME (USERPROFILE on Windows) is unset")
            }
            Self::RelativeWorkgraphHome(value) => {
                write!(formatter, "WORKGRAPH_HOME must be absolute: {value}")
            }
        }
    }
}

impl std::error::Error for PathsError {}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Flavour {
    Windows,
    Posix,
}

impl Flavour {
    fn of(os: Os) -> Self {
        match os {
            Os::Windows => Self::Windows,
            Os::Linux | Os::MacOs => Self::Posix,
        }
    }

    fn is_separator(self, character: char) -> bool {
        match self {
            Self::Windows => character == '\\' || character == '/',
            Self::Posix => character == '/',
        }
    }

    fn separator(self) -> char {
        match self {
            Self::Windows => '\\',
            Self::Posix => '/',
        }
    }
}

/// A resolved location: its path text in the flavour of the operating system it belongs to.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AppPath {
    flavour: Flavour,
    text: String,
}

impl AppPath {
    fn new(flavour: Flavour, text: String) -> Self {
        Self { flavour, text }
    }

    /// Appends one component with the flavour's separator, as `os.path.join` does.
    fn join(&self, component: &str) -> Self {
        let text = if self.text.is_empty() {
            component.to_owned()
        } else if self
            .text
            .chars()
            .last()
            .is_some_and(|c| self.flavour.is_separator(c))
        {
            format!("{}{component}", self.text)
        } else {
            format!("{}{}{component}", self.text, self.flavour.separator())
        };
        Self::new(self.flavour, text)
    }

    /// The path text, exactly as the platform would print it.
    pub fn as_str(&self) -> &str {
        &self.text
    }
}

impl fmt::Display for AppPath {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.text)
    }
}

/// Lexical normalisation as `PureWindowsPath` and `PurePosixPath` do it: repeated separators,
/// `.` components and trailing separators go, mixed separators become the flavour's own. `..` is
/// kept, as Python keeps it.
fn normalise(flavour: Flavour, raw: &str) -> String {
    let (drive, rest) = match flavour {
        Flavour::Windows => split_drive(raw),
        Flavour::Posix => ("", raw),
    };
    let absolute = rest.chars().next().is_some_and(|c| flavour.is_separator(c));
    let parts: Vec<&str> = rest
        .split(|c| flavour.is_separator(c))
        .filter(|part| !part.is_empty() && *part != ".")
        .collect();
    let mut out = String::from(drive);
    if absolute {
        out.push(flavour.separator());
    }
    out.push_str(&parts.join(&flavour.separator().to_string()));
    out
}

/// Splits a leading `X:` drive letter off a Windows path.
fn split_drive(raw: &str) -> (&str, &str) {
    let bytes = raw.as_bytes();
    if bytes.len() >= 2 && bytes[0].is_ascii_alphabetic() && bytes[1] == b':' {
        raw.split_at(2)
    } else {
        ("", raw)
    }
}

/// Absolute as `PurePath.is_absolute` decides it: POSIX needs a leading `/`, Windows needs a
/// drive followed by a separator.
fn is_absolute(flavour: Flavour, text: &str) -> bool {
    match flavour {
        Flavour::Posix => text.starts_with('/'),
        Flavour::Windows => {
            let (drive, rest) = split_drive(text);
            !drive.is_empty() && rest.chars().next().is_some_and(|c| flavour.is_separator(c))
        }
    }
}

/// The value when it is set and not empty.
fn present(value: &Option<String>) -> Option<&str> {
    value.as_deref().filter(|text| !text.is_empty())
}

/// An XDG base directory: trimmed, and used only when absolute (platformdirs ignores relative
/// values). The text is not normalised, as platformdirs does not normalise it.
fn xdg_base(value: &Option<String>) -> Option<AppPath> {
    let trimmed = present(value)?.trim();
    trimmed
        .starts_with('/')
        .then(|| AppPath::new(Flavour::Posix, trimmed.to_owned()))
}

/// The home directory as a path of the given flavour, or `NoHome`.
fn home_path(flavour: Flavour, env: &Environment) -> Result<AppPath, PathsError> {
    let raw = present(&env.home).ok_or(PathsError::NoHome)?;
    let trimmed = raw.trim_end_matches(|c| flavour.is_separator(c));
    // A bare root (`/`) has nothing to trim to, so it stays as it is.
    let text = if trimmed.is_empty() { raw } else { trimmed };
    Ok(AppPath::new(flavour, text.to_owned()))
}

/// Expands a leading `~` (`~` alone, `~/...`, and `~\...` on Windows) against the home directory.
fn expand_user(flavour: Flavour, raw: &str, env: &Environment) -> Result<String, PathsError> {
    let rest = match raw.strip_prefix('~') {
        Some(rest)
            if rest.is_empty()
                || rest.starts_with('/')
                || (flavour == Flavour::Windows && rest.starts_with('\\')) =>
        {
            rest
        }
        _ => return Ok(raw.to_owned()),
    };
    let home = home_path(flavour, env)?;
    Ok(format!("{}{rest}", home.as_str()))
}

/// The three platform base locations and the `AppPaths` derived from them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AppPaths {
    config_dir: AppPath,
    data_dir: AppPath,
    log_dir: AppPath,
}

impl AppPaths {
    /// Resolves the locations of contract section 7 for the given environment.
    pub fn resolve(env: &Environment) -> Result<Self, PathsError> {
        let flavour = Flavour::of(env.os);
        match present(&env.workgraph_home) {
            Some(raw) => {
                let expanded = expand_user(flavour, raw, env)?;
                if !is_absolute(flavour, &expanded) {
                    return Err(PathsError::RelativeWorkgraphHome(raw.to_owned()));
                }
                let base = AppPath::new(flavour, normalise(flavour, &expanded));
                Ok(Self {
                    config_dir: base.join("config"),
                    data_dir: base.join("data"),
                    log_dir: base.join("logs"),
                })
            }
            None => Self::platform_defaults(env),
        }
    }

    fn platform_defaults(env: &Environment) -> Result<Self, PathsError> {
        match env.os {
            Os::Windows => {
                let base = match present(&env.local_appdata) {
                    Some(raw) => AppPath::new(Flavour::Windows, normalise(Flavour::Windows, raw)),
                    None => home_path(Flavour::Windows, env)?
                        .join("AppData")
                        .join("Local"),
                };
                let data_dir = base.join("workgraph");
                Ok(Self {
                    config_dir: data_dir.clone(),
                    log_dir: data_dir.join("Logs"),
                    data_dir,
                })
            }
            Os::Linux => {
                let home = home_path(Flavour::Posix, env)?;
                let config_base = match xdg_base(&env.xdg_config_home) {
                    Some(base) => base,
                    None => home.join(".config"),
                };
                let data_base = match xdg_base(&env.xdg_data_home) {
                    Some(base) => base,
                    None => home.join(".local").join("share"),
                };
                let state_base = match xdg_base(&env.xdg_state_home) {
                    Some(base) => base,
                    None => home.join(".local").join("state"),
                };
                Ok(Self {
                    config_dir: config_base.join("workgraph"),
                    data_dir: data_base.join("workgraph"),
                    log_dir: state_base.join("workgraph").join("log"),
                })
            }
            Os::MacOs => {
                let home = home_path(Flavour::Posix, env)?;
                let config_dir = match xdg_base(&env.xdg_config_home) {
                    Some(base) => base.join("workgraph"),
                    None => home
                        .join("Library")
                        .join("Application Support")
                        .join("workgraph"),
                };
                let data_dir = match xdg_base(&env.xdg_data_home) {
                    Some(base) => base.join("workgraph"),
                    None => home
                        .join("Library")
                        .join("Application Support")
                        .join("workgraph"),
                };
                Ok(Self {
                    config_dir,
                    data_dir,
                    log_dir: home.join("Library").join("Logs").join("workgraph"),
                })
            }
        }
    }

    /// `<config>`: the directory of F01, F02 and F03.
    pub fn config_dir(&self) -> AppPath {
        self.config_dir.clone()
    }

    /// `<data>`: the directory of F04, F05, F06, F07, F08, F09 and F10.
    pub fn data_dir(&self) -> AppPath {
        self.data_dir.clone()
    }

    /// `<logs>`: the directory of F11.
    pub fn log_dir(&self) -> AppPath {
        self.log_dir.clone()
    }

    /// F01: `<config>/config.toml`.
    pub fn config_file(&self) -> AppPath {
        self.config_dir.join("config.toml")
    }

    /// F02: `<config>/workspaces`, holding `<slug>.toml` per workspace.
    pub fn workspace_config_dir(&self) -> AppPath {
        self.config_dir.join("workspaces")
    }

    /// F03: `<config>/api-token`.
    pub fn api_token_file(&self) -> AppPath {
        self.config_dir.join("api-token")
    }

    /// F04: `<data>/workgraph.db` (its `-wal` and `-shm` siblings are SQLite's).
    pub fn database_file(&self) -> AppPath {
        self.data_dir.join("workgraph.db")
    }

    /// F05: `<data>/analytics.duckdb`.
    pub fn analytics_file(&self) -> AppPath {
        self.data_dir.join("analytics.duckdb")
    }

    /// F06: `<data>/artifacts`.
    pub fn artifacts_dir(&self) -> AppPath {
        self.data_dir.join("artifacts")
    }

    /// F07: `<data>/worktrees`.
    pub fn worktrees_dir(&self) -> AppPath {
        self.data_dir.join("worktrees")
    }

    /// F09: `<data>/spool/claude-hooks`.
    pub fn spool_dir(&self) -> AppPath {
        self.data_dir.join("spool").join("claude-hooks")
    }

    /// F10: `<data>/backups`.
    pub fn backups_dir(&self) -> AppPath {
        self.data_dir.join("backups")
    }

    /// F08: `<data>/runs`.
    pub fn runs_dir(&self) -> AppPath {
        self.data_dir.join("runs")
    }
}
