VERSION = 1


def write(name: str, document: dict[str, Any]) -> None:
    document = {"vector": VECTOR, "file": name, "version": VERSION, **document}
    OUT.mkdir(parents=True, exist_ok=True)
    text = json.dumps(document, sort_keys=True, indent=2, ensure_ascii=False) + "\n"
    with (OUT / name).open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


