"""Golden vectors for the telemetry foundations (GV-07).

Writes ``golden/telemetry/*.json``, generated by running the Python reference implementation:

* ``redaction.json``    ``security/redaction.py``: every secret-value pattern, key-based redaction,
                        truncation, the size and depth bounds and ``summarize``.
* ``transcript.json``   ``integrations/claude_code/transcript.py``: ``parse_transcript`` and
                        ``tool_calls`` over generated subagent transcripts (JSONL plus sidecar).
* ``timing.json``       ``integrations/claude_code/timing.py``: ``classify`` and ``breakdown``.
* ``hook_payload.json`` ``integrations/claude_code/ingest.py``: the pure parts of hook payload
                        normalisation (``dedupe_key``, ``schema_version``, ``_sanitize``,
                        ``_tool_summary``, the ``Invalid`` wrap and ``_workgraph`` stamp done by
                        ``process_record`` before its database work) and ``TASK_KEY_RE``.

Every secret in here is an obviously fake placeholder built from repeated characters.

Run with ``uv run python tools/golden/gen_telemetry.py``. Output is sorted-key JSON, UTF-8, ``\\n``
line endings, so two runs produce identical bytes.
"""

