def _record(
    payload: Any, *, received_at: Any = "2026-10-14T08:54:31+00:00", env: Any = None
) -> dict[str, Any]:
    record: dict[str, Any] = {"payload": payload, "received_at": received_at}
    if env is not None:
        record["env"] = env
    return record


def _normalise(record: dict[str, Any], config: ClaudeIntegrationConfig) -> dict[str, Any]:
    """The pure steps of ``process_record`` before its database work, in the same order."""
    raw = record.get("payload") or {}
    if not isinstance(raw, dict) or "hook_event_name" not in raw:
        raw = {"hook_event_name": "Invalid", "original": raw}
    key = dedupe_key(record)
    payload = HookPayload.model_validate(raw)
    sanitized = _sanitize(raw, config)
    sanitized["_workgraph"] = {"schema_version": schema_version(raw), "source": "direct"}
    return {
        "normalised_payload_event": raw["hook_event_name"],
        "dedupe_key": key,
        "sanitized": sanitized,
        "tool_summary": _tool_summary(payload),
        "schema_version": schema_version(raw),
    }


